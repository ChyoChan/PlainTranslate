import Foundation

enum TranslationEngine: String {
    case apple, google
}

enum TranslationLanguageDefaults {
    static let source = "en"
    static let target = "zh-Hant"
    static let languages = ["zh-Hant", "en", "ja", "zh-Hans"]
}

enum TranslationInputError: Error { case empty, tooLong, sensitive, clipboardChanged }

/// Bound work without splitting or rewriting the selected text.
enum TranslationTextPlan {
    static let maximumCharacters = 40_000
    static let protectedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    static func validate(_ text: String, types: Set<String> = []) throws -> String {
        guard protectedTypes.isDisjoint(with: types) else { throw TranslationInputError.sensitive }
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            throw TranslationInputError.empty
        }
        guard text.count <= maximumCharacters else { throw TranslationInputError.tooLong }
        return text
    }

    static func isFreshCopy(baseline: Int?, current: Int) -> Bool {
        guard let baseline else { return false }
        return baseline != current
    }

    static func translate(_ text: String,
                          using engine: (String) async throws -> String) async throws -> String {
        let input = try validate(text)
        try Task.checkCancellation()
        let output = try await engine(input)
        try Task.checkCancellation()
        return output
    }
}

struct TranslationRequest: Equatable {
    let id = UUID()
    let text: String
    let source: String?
    let target: String
    let engine: TranslationEngine

    init(text: String, source: String?, target: String, engine: TranslationEngine = .apple) {
        self.text = text
        self.source = source
        self.target = target
        self.engine = engine
    }
}

/// Invalidates reads/results after another invocation, edits, cancellation or close.
struct TranslationGeneration {
    private(set) var current = UUID()
    @discardableResult mutating func advance() -> UUID { current = UUID(); return current }
    func accepts(_ token: UUID) -> Bool { token == current }
}

extension Notification.Name {
    static let translationCredentialsDidChange = Notification.Name("translationCredentialsDidChange")
}
